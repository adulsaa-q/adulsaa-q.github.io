import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
const require = createRequire(import.meta.url);
const engines = require(require.resolve("playwright", { paths: [process.env.Q_AUDIT_TOOLS || process.cwd()] }));
const engine = process.env.Q_AUDIT_BROWSER || "chromium";
const base = process.argv[2] || "http://localhost:4173";
const output = process.argv[3] || "/tmp/q-portfolio-audit";
const browser = await engines[engine].launch({ headless: true, ...(engine === "chromium" && process.env.Q_AUDIT_CHROME ? { executablePath: process.env.Q_AUDIT_CHROME } : {}) });
const checks = [], errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, ...(engine !== "firefox" ? { isMobile: true } : {}), colorScheme: "dark", reducedMotion: "reduce" });
  const page = await context.newPage();
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(base, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Switch to light theme" }).waitFor();
  await page.emulateMedia({ colorScheme: "light" });
  await page.getByRole("button", { name: "Switch to dark theme" }).waitFor();
  await page.getByRole("button", { name: "Switch to dark theme" }).click();
  await page.reload({ waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Switch to light theme" }).waitFor();
  checks.push("System theme, system changes, explicit preference persists on refresh");
  await page.getByRole("button", { name: "Open menu" }).tap();
  assert(await page.locator("main").evaluate(element => element.inert));
  await page.keyboard.press("Shift+Tab");
  assert.equal(await page.evaluate(() => document.activeElement.textContent), "Contact");
  await page.keyboard.press("Escape");
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute("aria-label")), "Open menu");
  assert.equal(await page.locator("main").evaluate(element => element.inert), false);
  checks.push("Touch menu, focus trap, Escape, focus restoration, inert background");
  await page.getByRole("button", { name: /Enlarge image:/ }).first().click();
  assert.equal(await page.locator("dialog[open]").count(), 1);
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("dialog[open]").count(), 0);
  checks.push("Hero image modal opens and escapes");
  await page.getByRole("tab", { name: "02 · Daily & Mix" }).click();
  await page.keyboard.press("ArrowRight");
  assert.equal(await page.getByRole("tab", { name: "03 · Hourly Heatmap" }).getAttribute("aria-selected"), "true");
  await page.locator(".artifact-carousel__zoom-btn").first().click();
  await page.keyboard.press("Escape");
  assert(await page.locator(".artifact-carousel__zoom-btn").first().evaluate(element => document.activeElement === element));
  checks.push("Carousel keyboard selection and modal focus restoration");
  await page.getByRole("link", { name: "Read case study" }).first().click();
  await page.waitForURL("**/work/ecommerce-sales-pipeline/");
  await page.goBack();
  await page.waitForURL(new URL("/", base).href);
  await page.goForward();
  await page.waitForURL("**/work/ecommerce-sales-pipeline/");
  checks.push("Direct routes, navigation, browser back/forward");
  const nojs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 640, height: 450 } });
  const staticPage = await nojs.newPage();
  await staticPage.goto(base);
  assert(await staticPage.locator('a[href="mailto:adulsaa.q@gmail.com"]').count());
  assert(await staticPage.locator("h1").isVisible());
  assert(await staticPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  checks.push("No-JavaScript identity, contact and 200% equivalent viewport reflow");
  assert.deepEqual(errors, []);
} finally {
  await mkdir(output, { recursive: true });
  await writeFile(path.join(output, "interactions.json"), JSON.stringify({ engine, version: browser.version(), checks, errors }, null, 2));
  await browser.close();
}
console.log(`${engine}: ${checks.length} interaction groups passed`);
